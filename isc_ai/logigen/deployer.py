"""Emit the ObjectScript deployer class of a catalog folder.

The generated Logi XML files travel inside a site class (one XData block per file), so the
reports move between environments in the CCR ItemSet like any code. After the class is loaded,
one call does the whole environment setup, in any environment (also LIVE, where no MCP runner
is allowed):

- Deploy() writes the files into the environment Logi folder (websys.Configuration.GetJReportPath()),
  checks each written file against the SHA-256 computed by the generator and grants EXECUTE on the
  catalog stored procedures (SQL grants do not travel in the ItemSet).
- Verify() only checks (files present with the expected hash, grants in place) and writes nothing.
"""
from __future__ import annotations

import hashlib
import pathlib
import re

# Placeholders (@NAME@) instead of str.format: the ObjectScript body is full of braces.
HEADER = """/// GENERATED by isc-ai logi - do not edit by hand.
/// Logi report files of the "@FOLDER@" catalog folder (catalog @CATALOG@), one XData block per file.
/// <p>The class travels in the CCR ItemSet like any code. After it is loaded in an environment, run
/// <method>Deploy</method> once: it writes the files into the Logi report folder, verifies their
/// SHA-256 and grants EXECUTE on the catalog stored procedures (grants do not travel in the ItemSet):
/// <example>Write $System.Status.GetErrorText(##class(@CLASSNAME@).Deploy())</example>
/// <method>Verify</method> checks files and grants without writing anything.</p>
Class @CLASSNAME@ Extends %RegisteredObject
{

/// Sub folder of the Logi report root (websys.Configuration.GetJReportPath()).
Parameter FOLDER = "@FOLDER@";

/// File name : XData block : SHA-256 of the generated file (lower case hex).
Parameter FILES = "@FILES@";

/// SQL stored procedures the Logi catalog calls (schema.procedure).
Parameter PROCEDURES = "@PROCEDURES@";

/// SQL role of the Logi JDBC user (TrakCare product convention).
Parameter SQLROLE = "@SQLROLE@";

/// Writes every file into the Logi report folder (or into pTargetDir when given), verifies each
/// file hash and, when pGrant is true, grants EXECUTE on PROCEDURES to SQLROLE.
/// pWritten returns "name:size" pairs of the files written.
ClassMethod Deploy(pTargetDir As %String = "", Output pWritten As %String, pGrant As %Boolean = 1) As %Status
{
	Set sc = $$$OK, pWritten = ""
	Try {
		Set sc = ..TargetDirectory(.pTargetDir)
		If $$$ISERR(sc) Quit
		If '##class(%File).DirectoryExists(pTargetDir), '##class(%File).CreateDirectoryChain(pTargetDir) {
			Set sc = $$$ERROR($$$GeneralError, "Cannot create directory " _ pTargetDir)
			Quit
		}
		Set files = $ListFromString(..#FILES)
		For i = 1:1:$ListLength(files) {
			Set name = $Piece($List(files, i), ":", 1), block = $Piece($List(files, i), ":", 2)
			Set xdata = ##class(%Dictionary.CompiledXData).%OpenId($ClassName() _ "||" _ block, 0)
			If '$IsObject(xdata) {
				Set sc = $$$ERROR($$$GeneralError, "Missing XData " _ block)
				Quit
			}
			Set file = ##class(%Stream.FileCharacter).%New()
			Set file.TranslateTable = "UTF8"
			Set sc = file.LinkToFile(pTargetDir _ name)
			If $$$ISERR(sc) Quit
			Do file.Clear()
			Set sc = file.CopyFrom(xdata.Data)
			If $$$ISOK(sc) Set sc = file.%Save()
			If $$$ISERR(sc) Quit
			Set pWritten = pWritten _ $ListBuild(name _ ":" _ file.Size)
		}
		If $$$ISERR(sc) Quit
		Set sc = ..CheckFiles(pTargetDir)
		If $$$ISERR(sc) Quit
		If pGrant Set sc = ..Grant()
	} Catch ex {
		Set sc = ex.AsStatus()
	}
	Quit sc
}

/// Grants EXECUTE on every catalog stored procedure to SQLROLE and checks the privilege.
ClassMethod Grant() As %Status
{
	Set sc = $$$OK
	Try {
		Set procedures = $ListFromString(..#PROCEDURES)
		For i = 1:1:$ListLength(procedures) {
@GRANTCALL@
		}
		// The privilege check is the verdict, whatever the grant helper returned
		Set sc = $System.Status.AppendStatus(sc, ..CheckGrants())
	} Catch ex {
		Set sc = ex.AsStatus()
	}
	Quit sc
}

/// Read-only check of the environment: every file present with the generated hash and EXECUTE
/// granted on every procedure. pReport returns one line per problem ("" when all is fine).
ClassMethod Verify(pTargetDir As %String = "", Output pReport As %String) As %Status
{
	Set pReport = ""
	Set sc = ..TargetDirectory(.pTargetDir)
	If $$$ISOK(sc) Set sc = $System.Status.AppendStatus(..CheckFiles(pTargetDir), ..CheckGrants())
	If $$$ISERR(sc) Set pReport = $System.Status.GetErrorText(sc)
	Quit sc
}

ClassMethod TargetDirectory(ByRef pTargetDir As %String) As %Status [ Private ]
{
	If pTargetDir = "" {
		Set root = ##class(websys.Configuration).GetJReportPath()
		If root = "" Quit $$$ERROR($$$GeneralError, "websys.Configuration JReport path is not set")
		Set pTargetDir = ##class(%File).NormalizeDirectory(..#FOLDER, root)
	}
	Set pTargetDir = ##class(%File).NormalizeDirectory(pTargetDir)
	Quit $$$OK
}

ClassMethod CheckFiles(pTargetDir As %String) As %Status [ Private ]
{
	Set sc = $$$OK
	Set files = $ListFromString(..#FILES)
	For i = 1:1:$ListLength(files) {
		Set name = $Piece($List(files, i), ":", 1), expected = $Piece($List(files, i), ":", 3)
		Set path = pTargetDir _ name
		If '##class(%File).Exists(path) {
			Set sc = $System.Status.AppendStatus(sc, $$$ERROR($$$GeneralError, "Missing file " _ path))
			Continue
		}
		Set stream = ##class(%Stream.FileBinary).%New()
		Do stream.LinkToFile(path)
		Set hash = $System.Encryption.SHAHashStream(256, stream)
		Set actual = ""
		For j = 1:1:$Length(hash) Set actual = actual _ $ZConvert($Translate($Justify($ZHex($Ascii(hash, j)), 2), " ", "0"), "L")
		If actual '= expected {
			Set sc = $System.Status.AppendStatus(sc, $$$ERROR($$$GeneralError, "Hash mismatch " _ path _ " expected " _ expected _ " actual " _ actual))
		}
	}
	Quit sc
}

ClassMethod CheckGrants() As %Status [ Private ]
{
	Set sc = $$$OK
	Set procedures = $ListFromString(..#PROCEDURES)
	For i = 1:1:$ListLength(procedures) {
		Set procedure = $List(procedures, i)
		// CheckPrivilege throws <UNDEFINED> when the procedure does not exist
		Try {
			Set granted = $SYSTEM.SQL.Security.CheckPrivilege(..#SQLROLE, 9, procedure, "e")
		} Catch {
			Set granted = 0
		}
		If granted '= 1 {
			Set sc = $System.Status.AppendStatus(sc, $$$ERROR($$$GeneralError, "Missing EXECUTE on " _ procedure _ " for " _ ..#SQLROLE))
		}
	}
	Quit sc
}
"""

XDATA = """
XData @BLOCK@ [ MimeType = application/xml ]
{
@CONTENT@
}
"""

DEFAULT_SQL_ROLE = "TrakCareSQLUserRole"

# Default grant: plain SQL, available in every IRIS namespace. SQLCODE 100 = already granted.
SQL_GRANT = """			Set statement = "GRANT EXECUTE ON " _ $List(procedures, i) _ " TO " _ ..#SQLROLE
			Set result = ##class(%SQL.Statement).%ExecDirect(, statement)
			If (result.%SQLCODE < 0) Set sc = $System.Status.AppendStatus(sc, $$$ERROR($$$GeneralError, statement _ ": " _ result.%Message))"""

# Site grant helper "Package.Class.Method", called as Method(procedure, role).
CLASS_METHOD = re.compile(r"^%?[A-Za-z][A-Za-z0-9]*(\.[A-Za-z][A-Za-z0-9]*)+$")


def grant_call(grant_method: str = "") -> str:
    """ObjectScript lines that grant EXECUTE on $List(procedures, i) to ..#SQLROLE."""
    if not grant_method:
        return SQL_GRANT
    if not CLASS_METHOD.match(grant_method) or grant_method.count(".") < 2:
        raise KeyError(f"grantMethod must be Package.Class.Method, got {grant_method!r}")
    class_name, method = grant_method.rsplit(".", 1)
    return f"			Do ##class({class_name}).{method}($List(procedures, i), ..#SQLROLE)"


def block_name(file_name: str) -> str:
    stem = re.sub(r"\.(cls|cat)\.xml$", lambda m: m.group(1).capitalize() + "Xml", file_name)
    return re.sub(r"[^A-Za-z0-9]", "", stem)


def _fill(template: str, values: dict[str, str]) -> str:
    for key, value in values.items():
        template = template.replace(f"@{key}@", value)
    return template


def deployer_source(classname: str, folder: str, catalog: str, files: dict[str, bytes],
                    procedures: list[str], sql_role: str = DEFAULT_SQL_ROLE, grant_method: str = "") -> str:
    """files: generated file name -> exact bytes (hashed as written by the generator)."""
    entries = ",".join(f"{name}:{block_name(name)}:{hashlib.sha256(data).hexdigest()}" for name, data in files.items())
    text = _fill(HEADER, {"CLASSNAME": classname, "FOLDER": folder, "CATALOG": catalog, "FILES": entries,
                          "PROCEDURES": ",".join(procedures), "SQLROLE": sql_role,
                          "GRANTCALL": grant_call(grant_method)})
    for name, data in files.items():
        text += _fill(XDATA, {"BLOCK": block_name(name), "CONTENT": data.decode("utf-8").rstrip("\n")})
    return text + "\n}\n"


def deployer_path(source_root: pathlib.Path, classname: str) -> pathlib.Path:
    return source_root.joinpath(*classname.split(".")).with_suffix(".cls")


def render_deployer(classname: str, folder: str, catalog: str, output_folder: pathlib.Path,
                    procedures: list[str], sql_role: str = DEFAULT_SQL_ROLE, grant_method: str = "") -> str:
    files = {p.name: p.read_bytes() for p in sorted(output_folder.glob("*.xml"))}
    return deployer_source(classname, folder, catalog, files, procedures, sql_role, grant_method)


def write_deployer(source_root: pathlib.Path, classname: str, folder: str, catalog: str,
                   output_folder: pathlib.Path, procedures: list[str], sql_role: str = DEFAULT_SQL_ROLE,
                   grant_method: str = "") -> pathlib.Path:
    path = deployer_path(source_root, classname)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_deployer(classname, folder, catalog, output_folder, procedures, sql_role, grant_method),
                    encoding="utf-8", newline="\n")
    return path